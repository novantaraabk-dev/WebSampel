export interface PermohonanSuratItem {
  id: string;
  jenisSurat: string;
  urlSurat?: string;
  klasifikasi: string;
  kodeSurat: string;
  uraian: string;
  keterangan?: string;
  isActive?: boolean;
  favorit?: boolean;
  mandiri?: boolean;
  jenis?: 1 | 2 | 3 | 4; // 1 / 3 = Bawaan Sistem, 2 / 4 = Surat Khusus Desa
  kategori?: 'Kependudukan' | 'Pernikahan' | 'Pertanahan' | 'Ekonomi & Usaha' | 'Sosial & Bantuan' | 'Umum';
  pemohonSurat?: 'warga' | 'non_warga';
  masaBerlaku?: string;
  masaBerlakuValue?: number;
  satuanMasaBerlaku?: 'D' | 'W' | 'M' | 'Y' | 'd' | 'w' | 'y';
  orientasi?: 'Potrait' | 'Landscape';
  ukuran?: string;
  marginGlobal?: boolean;
  margin?: OpenSidMargin;
  header?: 0 | 1 | 2; // 1 = Semua Halaman, 2 = Halaman Awal Saja, 0 = Tanpa Kop
  footer?: boolean;
  logoGaruda?: boolean;
  qrCode?: boolean;
  qrCodeTte?: boolean;
  qrSettings?: OpenSidQrSignatureSettings;
  kecamatan?: boolean;
  formatNomorGlobal?: boolean;
  formatNomor?: string;
  sumberPendudukBerulang?: boolean;
  syaratSurat?: string[];
  lampiran?: string[];
  lampiranConfig?: LampiranBindingConfig[];
  template?: string;
  templateDesa?: string;
  formIsian?: OpenSidFormIsian;
  kodeIsian?: OpenSidKodeIsian[];
  createdAt?: string;
  updatedAt?: string;
}

